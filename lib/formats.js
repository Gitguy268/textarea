// Text -> file format converters.
//
// Everything here is a pure function from a note to a string (or bytes), so it
// can be unit tested under Node without a browser. The note shape is shared by
// every exporter:
//
//   { text, title, style, hash, exportedAt }
//
// `text` is the raw markdown-ish source, `style` the inline style attribute the
// author may have added to <article> through DevTools, `hash` the current URL
// hash and `exportedAt` an ISO timestamp.

// Lives in a module of its own because the note's title needs it at boot and
// nothing else here is needed until something is exported.
import {sanitizeFilename} from './filename.js'

export {sanitizeFilename}

function ensureTrailingNewline(text) {
  return text.endsWith('\n') ? text : text + '\n'
}

function escapeXmlText(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
}

function escapeXmlAttribute(value) {
  return escapeXmlText(value).replace(/"/g, '&quot;')
}

/**
 * RFC 4180 CSV, with the formula prefixes neutralised.
 *
 * Freeform notes have no inherent table structure, so the honest mapping is
 * one row per line in a single `text` column; a document that is already
 * comma separated keeps its rows intact because quotes are escaped rather than
 * the content being split.
 *
 * The single quote in front of a leading `=`, `+`, `-`, `@`, tab or CR is the
 * standard defence against CSV formula injection (CWE-1236): a spreadsheet
 * evaluates a cell by its first character, so a note line like
 * `=HYPERLINK(...)` should not become a live formula, or a DDE payload, in
 * whatever workbook the reader opens the export in.
 */
export function toCsv(text) {
  const FORMULA_PREFIX = /^[=+\-@\t\r]/
  const rows = ['line,text']
  const lines = text === '' ? [] : text.split('\n')
  // A trailing newline in the source is not a row.
  if (lines.length > 1 && lines[lines.length - 1] === '') lines.pop()

  lines.forEach((line, i) => {
    const cell = FORMULA_PREFIX.test(line) ? `'${line}` : line
    rows.push(`${i + 1},"${cell.replace(/"/g, '""')}"`)
  })
  // RFC 4180 mandates CRLF, including after the last record.
  return rows.join('\r\n') + '\r\n'
}

function toJson(note) {
  return JSON.stringify(
    {
      title: note.title,
      exportedAt: note.exportedAt,
      hash: note.hash,
      style: note.style ?? null,
      text: note.text,
    },
    null,
    2,
  ) + '\n'
}

/**
 * CDATA cannot contain the sequence `]]>`, so any occurrence is split across two
 * CDATA sections. Doing it this way means the text survives verbatim, which
 * matters for notes full of angle brackets and ampersands.
 */
function toCdata(text) {
  return String(text).split(']]>').join(']]]]><![CDATA[>')
}

function toXml(note) {
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<note xmlns="https://textarea.my/ns/1">',
    `  <title>${escapeXmlText(note.title)}</title>`,
    `  <exportedAt>${escapeXmlText(note.exportedAt)}</exportedAt>`,
  ]
  if (note.hash) lines.push(`  <source>${escapeXmlText(note.hash)}</source>`)
  if (note.style) lines.push(`  <style>${escapeXmlText(note.style)}</style>`)
  // The content starts on the <![CDATA[ line so the first text line is not
  // preceded by whitespace, which would show up as a leading blank line.
  lines.push('  <text><![CDATA[' + toCdata(note.text) + ']]></text>')
  lines.push('</note>')
  return lines.join('\n')
}

/**
 * RTF 1.0. Unicode needs care: RTF is a 7-bit format, so every code unit above
 * 127 becomes a `\uN?` escape. Characters outside the Basic Multilingual Plane
 * arrive as a surrogate pair and are emitted as two escapes, which is what RTF
 * readers expect.
 */
export function toRtf(text) {
  let body = ''
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i)
    const char = text[i]
    if (char === '\\') body += '\\\\'
    else if (char === '{') body += '\\{'
    else if (char === '}') body += '\\}'
    else if (char === '\n') body += '\\par\n'
    else if (char === '\t') body += '\\tab '
    else if (code < 128) body += char
    else body += '\\u' + (code > 32767 ? code - 65536 : code) + '?'
  }

  return [
    '{\\rtf1\\ansi\\ansicpg1252\\deff0',
    '{\\fonttbl{\\f0\\fnil\\fcharset0 Helvetica;}}',
    '{\\colortbl;\\red0\\green0\\blue0;}',
    '\\f0\\fs22 ',
    body,
    '}',
  ].join('\n') + '\n'
}

const TEX_SPECIALS = /[\\{}$&#^_~%]/g

function texEscapeInline(line) {
  return line.replace(TEX_SPECIALS, (char) => '\\' + char)
}

/**
 * A LaTeX `article` with a monospace block for fenced code. Verbatim is used
 * rather than `lstlisting` so the output compiles with no package setup.
 */
export function toTex(note) {
  const out = [
    '% Generated by textarea.my',
    '\\documentclass[11pt,a4paper]{article}',
    '\\usepackage[utf8]{inputenc}',
    '\\usepackage[T1]{fontenc}',
    '\\usepackage[margin=2.5cm]{geometry}',
    '\\usepackage{parskip}',
    '\\usepackage{hyperref}',
    '',
    '\\title{' + texEscapeInline(note.title) + '}',
    '\\date{' + texEscapeInline(note.exportedAt.slice(0, 10)) + '}',
    '',
    '\\begin{document}',
    '\\maketitle',
    '',
  ]

  const blocks = note.text.split(/^(```[^\n]*\n[\s\S]*?\n```|~~~[^\n]*\n[\s\S]*?\n~~~)$/my)
  for (const block of blocks) {
    if (block === undefined || block === '') continue
    if (/^(```|~~~)/.test(block)) {
      const code = block.replace(/^(```|~~~)[^\n]*\n/, '').replace(/\n(```|~~~)$/, '')
      out.push('\\begin{verbatim}')
      out.push(code)
      out.push('\\end{verbatim}')
      out.push('')
    } else {
      for (const line of block.split('\n')) {
        out.push(texEscapeInline(line))
      }
      out.push('')
    }
  }

  out.push('\\end{document}')
  return out.join('\n')
}

/**
 * YAML front matter plus the note as a literal block scalar. The indentation and
 * the `-` chomping indicator matter: `|-` strips the final newline, and any line
 * that is empty or has trailing spaces has to be written out in full or the
 * parser folds it wrongly.
 */
export function toYaml(note) {
  // A scalar that YAML would read back as a number, a boolean or null has to be
  // quoted, otherwise the note's title silently changes type.
  const AMBIGUOUS = /^(?:true|false|null|yes|no|on|off|~|-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?|\.inf|\.nan)$/i

  const scalar = (value) => {
    if (typeof value !== 'string') return JSON.stringify(value)
    if (/[^\x20-\x7e]/.test(value)) return JSON.stringify(value)
    if (value === '' || AMBIGUOUS.test(value) || /^[\s>|&*!%@`?{}[\],#-]/.test(value)) {
      return JSON.stringify(value)
    }
    if (/:\s|\s#/.test(value) || /:\s*$/.test(value)) return JSON.stringify(value)
    return value
  }

  const lines = [
    'title: ' + scalar(note.title),
    'exportedAt: ' + scalar(note.exportedAt),
  ]
  if (note.hash) lines.push('source: ' + scalar(note.hash))
  if (note.style) lines.push('style: ' + scalar(note.style))
  lines.push('text: |-')
  for (const line of note.text.replace(/\n$/, '').split('\n')) {
    lines.push(line === '' ? '' : '  ' + line)
  }
  return lines.join('\n') + '\n'
}

/**
 * Wrap the already-rendered article markup in a standalone document. The caller
 * passes the page's own CSS text so the exported file is self-contained and
 * needs no network access to look right.
 */
function toHtml(note, { bodyHtml, css, title }) {
  const parts = [
    '<!DOCTYPE html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    `<title>${escapeXmlText(title ?? note.title)}</title>`,
    '<meta name="generator" content="textarea.my">',
    `<meta name="exportedAt" content="${escapeXmlAttribute(note.exportedAt)}">`,
    note.hash ? `<meta name="source" content="${escapeXmlAttribute(note.hash)}">` : null,
    '<style>' + css.trim() + '</style>',
    '</head>',
    '<body>',
    bodyHtml,
    '</body>',
    '</html>',
    '',
  ]
  return parts.filter((part) => part !== null).join('\n')
}

/**
 * The exporter registry. `ext` drives the download name, `mime` the Blob type
 * and the `showSaveFilePicker` accept map, `label` the menu text.
 *
 * `html` is special-cased by the caller because it needs the live page CSS and
 * rendered markup; it is still listed here so it appears in the format menu.
 */
export const FORMATS = [
  {id: 'txt', label: 'Plain text', ext: 'txt', mime: 'text/plain'},
  {id: 'md', label: 'Markdown', ext: 'md', mime: 'text/markdown'},
  {id: 'html', label: 'HTML page', ext: 'html', mime: 'text/html', needs: 'html'},
  {id: 'json', label: 'JSON', ext: 'json', mime: 'application/json'},
  {id: 'csv', label: 'CSV', ext: 'csv', mime: 'text/csv'},
  {id: 'xml', label: 'XML', ext: 'xml', mime: 'application/xml'},
  {id: 'rtf', label: 'RTF (Word)', ext: 'rtf', mime: 'application/rtf'},
  {id: 'tex', label: 'LaTeX', ext: 'tex', mime: 'application/x-tex'},
  {id: 'yml', label: 'YAML', ext: 'yml', mime: 'text/yaml'},
]

export const DEFAULT_FORMAT = 'txt'

export function getFormat(id) {
  return FORMATS.find((format) => format.id === id) ?? FORMATS[0]
}

/**
 * Render a note in the requested format. Returns `{ text, mime }`.
 *
 * `context.html` must supply `{ bodyHtml, css }` for the `html` format; when it
 * is absent the raw note text is used, which keeps this function usable in
 * tests and in the ZIP writer.
 */
export function convert(note, formatId, context = {}) {
  const format = getFormat(formatId)

  switch (format.id) {
    case 'html': {
      const bodyHtml = context.html?.bodyHtml ?? '<pre>' + escapeXmlText(note.text) + '</pre>'
      const css = context.html?.css ?? 'body { font: 18px/1.5 system-ui; white-space: pre-wrap; }'
      return {text: toHtml(note, {bodyHtml, css, title: context.html?.title}), mime: format.mime}
    }
    case 'md':
      return {text: ensureTrailingNewline(note.text), mime: format.mime}
    case 'json':
      return {text: toJson(note), mime: format.mime}
    case 'csv':
      return {text: toCsv(note.text), mime: format.mime}
    case 'xml':
      return {text: toXml(note), mime: format.mime}
    case 'rtf':
      return {text: toRtf(note.text), mime: format.mime}
    case 'tex':
      return {text: toTex(note), mime: format.mime}
    case 'yml':
      return {text: toYaml(note), mime: format.mime}
    default:
      return {text: note.text, mime: format.mime}
  }
}
